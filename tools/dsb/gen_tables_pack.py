# Generates rtl/sound/dsb_tables_pack.svh: dsb_mpeg's window and misc tables
# (rtl/sound/dsb_tables.svh, tools/dsb/gen_tables.py) packed into ONE 256 x 40
# ROM by their symmetries, for dsb_mpeg's TBL_PACK. Read from dsb_tables.svh
# itself, so the packed values are the same integers by construction, and
# every symmetry the packing relies on is checked on those values first:
#   window: win[512-i] == -win[i], except i % 64 == 0 where win[512-i] == win[i]
#   cos:    misc[64-k] == -misc[k] for k = 1..63
# Layout: words 0..128 {win[2w+1], win[2w]} (18 bits each, win[0..256]);
# words 129..161 cos[0..32]; words 162..243 misc[64..145] (misc_a + 98).
#
#   python3 tools/dsb/gen_tables_pack.py [rtl/sound/dsb_tables.svh] [out]
import re, sys
src = sys.argv[1] if len(sys.argv) > 1 else 'rtl/sound/dsb_tables.svh'
dst = sys.argv[2] if len(sys.argv) > 2 else 'rtl/sound/dsb_tables_pack.svh'
t = open(src).read()
win, misc = [None] * 512, [None] * 146
for i, v in re.findall(r'win\[(\d+)\] = (\d+);', t):
    v = int(v); win[int(i)] = v - (1 << 18) if v >> 17 else v
for i, v in re.findall(r"misc\[(\d+)\] = 32'd(\d+);", t):
    v = int(v); misc[int(i)] = v - (1 << 32) if v >> 31 else v
assert None not in win and None not in misc
for i in range(1, 512):
    want = win[512 - i] if i % 64 == 0 else -win[512 - i]
    assert win[i] == want or i <= 256, (i, win[i], win[512 - i])
    if i > 256:
        assert win[i] == want, i
for k in range(1, 64):
    assert misc[64 - k] == -misc[k], k
for v in misc:
    assert -(1 << 24) <= v < (1 << 24)          # fits the 25 bits dsb_mpeg reads
rom = [0] * 256
for w in range(129):
    lo = win[2 * w] & 0x3ffff
    hi = (win[2 * w + 1] & 0x3ffff) if 2 * w + 1 <= 256 else 0
    rom[w] = (hi << 18) | lo
for k in range(33):
    rom[129 + k] = misc[k] & 0x1ffffff
for j in range(64, 146):
    rom[j + 98] = misc[j] & 0x1ffffff
assert 145 + 98 < 256
# check: unpack every index the decoder can ask for, as dsb_mpeg does
def rd_win(a):
    hi = a > 256
    idx = (512 - a) & 511 if hi else a
    v = rom[idx >> 1] >> (18 if idx & 1 else 0) & 0x3ffff
    v = v - (1 << 18) if v >> 17 else v
    return -v if (hi and a % 64) else v
def rd_misc(a):
    if a < 64:
        hi = a > 32; idx = (64 - a) & 63 if hi else a
        v = rom[129 + idx] & 0x1ffffff
    else:
        hi = False; v = rom[a + 98] & 0x1ffffff
    v = v - (1 << 25) if v >> 24 else v
    return -v if hi else v
assert all(rd_win(a) == win[a] for a in range(512))
assert all(rd_misc(a) == misc[a] for a in range(146))
out = ['// Generated by tools/dsb/gen_tables_pack.py from dsb_tables.svh -- do not edit.',
       '// dsb_mpeg TBL_PACK: window and misc in one 256 x 40 ROM (layout in the generator).',
       'initial begin']
for i, v in enumerate(rom):
    out.append(f"  trom[{i}] = 40'h{v:010x};")
out.append('end')
open(dst, 'w').write('\n'.join(out) + '\n')
print('ok: 512 window + 146 misc entries in 244 words, every read checked')

// The SCSP's ROM tables for rtl/sound/scsp/, from MAME 0.289 scsp.cpp's own
// formulas (via scsp_ref.h, whose tables equal MAME's dump -- scsp_replay).
// Data derived from BSD-3-Clause code (ElSemi, R. Belmont); see THIRD_PARTY.md.
//
//   scsp_tables_gen <dir>   writes scsp_eg.hex (1,024 x 13), scsp_pscale.hex
//   (2,048 x 9: PSCALES[s][i], index s << 8 | i), scsp_ascale.hex (2,048 x 9),
//   and scsp_tables.svh (AR / DR rates, LFO phase steps, level factors).
#include "scsp_ref.h"
#include <cstdio>
#include <string>

using namespace scspref;

int main(int argc, char **argv) {
	std::string d = argc > 1 ? argv[1] : ".";
	static Tables T;
	FILE *f = fopen((d + "/scsp_eg.hex").c_str(), "w");
	for (int i = 0; i < 0x400; i++) fprintf(f, "%04x\n", T.EG_TABLE[i]);
	fclose(f);
	f = fopen((d + "/scsp_pscale.hex").c_str(), "w");
	for (int s = 0; s < 8; s++) for (int i = 0; i < 256; i++) fprintf(f, "%03x\n", T.PSCALES[s][i]);
	fclose(f);
	f = fopen((d + "/scsp_ascale.hex").c_str(), "w");
	for (int s = 0; s < 8; s++) for (int i = 0; i < 256; i++) fprintf(f, "%03x\n", T.ASCALES[s][i]);
	fclose(f);
	int mx = 0;
	for (int s = 0; s < 8; s++) for (int i = 0; i < 256; i++) { mx = std::max(mx, T.PSCALES[s][i]); mx = std::max(mx, T.ASCALES[s][i]); }
	fprintf(stderr, "scale max %d, EG max %d\n", mx, T.EG_TABLE[0x3ff]);
	f = fopen((d + "/scsp_tables.svh").c_str(), "w");
	fprintf(f, "// GENERATED by sim/sound/scsp_tables_gen.cpp -- MAME 0.289 scsp.cpp's tables\n// (BSD-3-Clause, ElSemi, R. Belmont; THIRD_PARTY.md). Do not edit.\n\n");
	fprintf(f, "function automatic logic [26:0] scsp_artab(input logic [5:0] i);\n  case (i)\n");
	for (int i = 0; i < 64; i++) fprintf(f, "    6'd%d: scsp_artab = 27'd%d;\n", i, T.ARTABLE[i]);
	fprintf(f, "    default: scsp_artab = 27'd0;\n  endcase\nendfunction\n\n");
	fprintf(f, "function automatic logic [18:0] scsp_drtab(input logic [5:0] i);\n  case (i)\n");
	for (int i = 0; i < 64; i++) { if (T.DRTABLE[i] >= (1 << 19)) { fprintf(stderr, "DR too wide\n"); return 1; } fprintf(f, "    6'd%d: scsp_drtab = 19'd%d;\n", i, T.DRTABLE[i]); }
	fprintf(f, "    default: scsp_drtab = 19'd0;\n  endcase\nendfunction\n\n");
	fprintf(f, "// LFO phase step, (u32)(256.0f * (LFOFreq[f] * 256.0f / 44100.0f))\n");
	fprintf(f, "function automatic logic [8:0] scsp_lfostep(input logic [4:0] i);\n  case (i)\n");
	for (int i = 0; i < 32; i++) {
		float step = (float)LFOFreq[i] * 256.0f / 44100.0f;
		uint32_t ps = (uint32_t)((float)(1 << LFO_SHIFT) * step);
		fprintf(f, "    5'd%d: scsp_lfostep = 9'd%u;\n", i, ps);
	}
	fprintf(f, "    default: scsp_lfostep = 9'd0;\n  endcase\nendfunction\n");
	fclose(f);
	return 0;
}

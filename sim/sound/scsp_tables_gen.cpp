// The SCSP's ROM tables for rtl/sound/scsp/, from MAME 0.289 scsp.cpp's own
// formulas (via scsp_ref.h, whose tables equal MAME's dump -- scsp_replay).
// Data derived from BSD-3-Clause code (ElSemi, R. Belmont); see THIRD_PARTY.md.
//
//   scsp_tables_gen <dir> [tables.bin]   writes scsp_eg.hex (1,024 x 13),
//   scsp_lfoscale.hex (the two LFOs' scales, 4,096 x 9) and scsp_lfonoise.svh
//   (the noise wave, R909), scsp_rate.hex
//   (AR / DR, 128 x 27), scsp_tables.svh (LFO phase steps), and with MAME's
//   tables.bin (p16) scsp_lfonoise.hex (the noise LFO, 256 x 8, for the benches).
#include "scsp_ref.h"
#include <cstdio>
#include <string>

using namespace scspref;

int main(int argc, char **argv) {
	std::string d = argc > 1 ? argv[1] : ".";
	static Tables T;
	FILE *f = fopen((d + "/scsp_eg.hex").c_str(), "w");
	for (int i = 0; i < 0x400; i++) fprintf(f, "%04x\n", T.EG_TABLE[i]);
	fclose(f);
	// the noise LFO's 256 values, MAME's machine().rand() (from a p16 tables.bin)
	if (argc > 2) {
		FILE *t = fopen(argv[2], "rb");
		static int buf[0x10000 * 2 + 0x400 + 64 * 2 + 8 * 256 * 2 + 256 * 2];
		size_t want = sizeof(s32) * 0x400 + sizeof(int) * (0x10000 * 2 + 64 * 2 + 8 * 256 * 2);   // ALFO_NOI
		if (!t || fseek(t, long(want), SEEK_SET) != 0 || fread(buf, sizeof(int), 256, t) != 256) { fprintf(stderr, "no noise table\n"); return 1; }
		fclose(t);
		f = fopen((d + "/scsp_lfonoise.hex").c_str(), "w");
		for (int i = 0; i < 256; i++) fprintf(f, "%02x\n", buf[i] & 0xff);
		fclose(f);
	}
	// THE LFOs (R909, was R858's 16,384 x 9 with the waves baked in, 18 M10K):
	// the two scale tables in ROM and the waves in logic in front of it.
	// scsp_lfoscale.hex is 4,096 x 9: [0, 2K) PSCALES read flat, at LFOS * 256 +
	// wave + 128, as MAME's pointer reads it (index 256 is the next row's first;
	// past PSCALES[7], ASCALES[0][0], which is where [2K, 4K) begins); [2K, 4K)
	// ASCALES[LFOS][wave]. The waves are MAME's formulas (m2_scsp_lfo) and the
	// noise wave its 256 values, scsp_lfonoise.svh. The noise needs MAME's
	// table (tables.bin); without it, MAME's defaults stand in (0 / 128).
	{
		static int an[256];
		for (int i = 0; i < 256; i++) an[i] = 0;
		if (argc > 2) {
			FILE *t = fopen(argv[2], "rb");
			static int nb[256];
			size_t want = sizeof(s32) * 0x400 + sizeof(int) * (0x10000 * 2 + 64 * 2 + 8 * 256 * 2);
			if (!t || fseek(t, long(want), SEEK_SET) != 0 || fread(nb, sizeof(int), 256, t) != 256) { fprintf(stderr, "no noise table\n"); return 1; }
			fclose(t);
			for (int i = 0; i < 256; i++) an[i] = nb[i] & 0xff;
		}
		const int *flat = &T.PSCALES[0][0];   // PSCALES then ASCALES, as in MAME's class
		f = fopen((d + "/scsp_lfoscale.hex").c_str(), "w");
		for (int i = 0; i < 4096; i++) fprintf(f, "%03x\n", flat[i]);
		fclose(f);
		f = fopen((d + "/scsp_lfonoise.svh").c_str(), "w");
		fprintf(f, "// GENERATED by sim/sound/scsp_tables_gen.cpp -- MAME 0.289 scsp.cpp's noise LFO,\n// machine().rand() & 0xff (BSD-3-Clause, ElSemi, R. Belmont; THIRD_PARTY.md). Do not edit.\n\n");
		fprintf(f, "function automatic logic [7:0] scsp_lfonoise(input logic [7:0] i);\n  case (i)\n");
		for (int i = 0; i < 256; i++) fprintf(f, "    8'd%d: scsp_lfonoise = 8'd%d;\n", i, an[i]);
		fprintf(f, "    default: scsp_lfonoise = 8'd0;\n  endcase\nendfunction\n");
		fclose(f);
		f = fopen((d + "/scsp_rate.hex").c_str(), "w");
		for (int i = 0; i < 64; i++) fprintf(f, "%07x\n", T.ARTABLE[i]);
		for (int i = 0; i < 64; i++) fprintf(f, "%07x\n", T.DRTABLE[i]);
		fclose(f);
	}
	int mx = 0;
	for (int s = 0; s < 8; s++) for (int i = 0; i < 256; i++) { mx = std::max(mx, T.PSCALES[s][i]); mx = std::max(mx, T.ASCALES[s][i]); }
	fprintf(stderr, "scale max %d, EG max %d\n", mx, T.EG_TABLE[0x3ff]);
	f = fopen((d + "/scsp_tables.svh").c_str(), "w");
	fprintf(f, "// GENERATED by sim/sound/scsp_tables_gen.cpp -- MAME 0.289 scsp.cpp's tables\n// (BSD-3-Clause, ElSemi, R. Belmont; THIRD_PARTY.md). Do not edit.\n\n");
	fprintf(f, "function automatic logic [26:0] scsp_artab(input logic [5:0] i);\n  case (i)\n");
	for (int i = 0; i < 64; i++) fprintf(f, "    6'd%d: scsp_artab = 27'd%d;\n", i, T.ARTABLE[i]);
	fprintf(f, "    default: scsp_artab = 27'd0;\n  endcase\nendfunction\n\n");
	fprintf(f, "function automatic logic [18:0] scsp_drtab(input logic [5:0] i);\n  case (i)\n");
	for (int i = 0; i < 64; i++) { if (T.DRTABLE[i] >= (1 << 19)) { fprintf(stderr, "DR too wide\n"); return 1; } fprintf(f, "    6'd%d: scsp_drtab = 19'd%d;\n", i, T.DRTABLE[i]); }
	fprintf(f, "    default: scsp_drtab = 19'd0;\n  endcase\nendfunction\n\n");
	fprintf(f, "// LFO phase step, (u32)(256.0f * (LFOFreq[f] * 256.0f / 44100.0f))\n");
	fprintf(f, "function automatic logic [8:0] scsp_lfostep(input logic [4:0] i);\n  case (i)\n");
	for (int i = 0; i < 32; i++) {
		float step = (float)LFOFreq[i] * 256.0f / 44100.0f;
		uint32_t ps = (uint32_t)((float)(1 << LFO_SHIFT) * step);
		fprintf(f, "    5'd%d: scsp_lfostep = 9'd%u;\n", i, ps);
	}
	fprintf(f, "    default: scsp_lfostep = 9'd0;\n  endcase\nendfunction\n");
	fclose(f);
	return 0;
}

#!/usr/bin/env python3
# R952: AN OLD-AGAINST-NEW MITER FOR "SMALLER, IDENTICAL" CHANGES.
#
#   sim/miter/miter.py <module> <old.sv> <new.sv> <outdir>
#
# Writes <outdir>/<module>_old.sv and <module>_new.sv (the two sources with the
# module renamed) and <outdir>/<module>_miter.sv: a module called <module>,
# with <module>'s own parameters and ports, that drives both copies from the
# same inputs, presents the NEW copy's outputs, and compares EVERY output of
# the two on every rising edge of clk. The count and the first mismatches are
# printed by a final block (the bench calls final(), or Verilator's exit does).
# Build the module's existing bench against <outdir>/<module>_miter.sv with
# --top-module <module> in place of the module's source: the bench then runs
# unchanged and every cycle of it is a check that the change is invisible.
#
# The port list must be ANSI style, one or more names per input/output line
# (this repository's style); parameters are passed through by name.
import re, sys, os

mod, old_p, new_p, out = sys.argv[1:5]
os.makedirs(out, exist_ok=True)

def strip_comments(t):
    t = re.sub(r'/\*.*?\*/', '', t, flags=re.S)
    return re.sub(r'//[^\n]*', '', t)

def rename(src, suffix):
    t = open(src).read()
    t2, n = re.subn(r'(\bmodule\s+)' + re.escape(mod) + r'\b', r'\g<1>' + mod + suffix, t, count=1)
    assert n == 1, f'module {mod} not found in {src}'
    return t2

new_t = strip_comments(open(new_p).read())
m = re.search(r'(\(\*[^)]*\*\)\s*)?\bmodule\s+' + re.escape(mod) + r'\b', new_t)
head = new_t[m.start():]
# header: "module X #( ... ) ( ... );"
depth = 0; i = head.index('module'); j = i; hdr_end = None
k = head.index(mod) + len(mod)
s = head[k:]
# find the end of the port list: the first ');' at paren depth 0 after the ports open
pos = 0; params = ''; ports = ''
s_nc = s
def match_paren(txt, start):
    d = 0
    for q in range(start, len(txt)):
        if txt[q] == '(': d += 1
        elif txt[q] == ')':
            d -= 1
            if d == 0: return q
    raise SystemExit('unbalanced')
p = 0
while s[p].isspace(): p += 1
if s[p] == '#':
    a = s.index('(', p); b = match_paren(s, a)
    params = s[a+1:b]; p = b + 1
a = s.index('(', p); b = match_paren(s, a)
ports = s[a+1:b]

pnames = []
for line in strip_comments(params).split('\n'):
    mm = re.match(r'\s*parameter\s+(.*)', line)
    if mm:
        body = mm.group(1)
        name = re.search(r'(\w+)\s*=', body).group(1)
        pnames.append(name)

ins, outs = [], []
for line in strip_comments(ports).split('\n'):
    mm = re.match(r'\s*(input|output)\b(.*)', line)
    if not mm: continue
    body = mm.group(2).strip().rstrip(',')
    body = re.sub(r'\[[^\]]*\]', ' ', body)                  # widths
    body = re.sub(r'\b(logic|wire|reg|signed|unsigned|bit)\b', ' ', body)
    names = [x.strip() for x in body.split(',') if x.strip()]
    (ins if mm.group(1) == 'input' else outs).extend(names)

open(f'{out}/{mod}_old.sv', 'w').write(rename(old_p, '_old'))
open(f'{out}/{mod}_new.sv', 'w').write(rename(new_p, '_new'))

pp = ', '.join(f'.{n}({n})' for n in pnames)
w = []
w.append(f'// generated by sim/miter/miter.py: {mod}, old ({old_p}) against new ({new_p})')
w.append('/* verilator lint_off DECLFILENAME */')
w.append(f'module {mod} #(' + params + ') (' + ports + ');')
for n in outs:
    w.append(f'  wire [$bits({n})-1:0] mo_{n};')
w.append(f'  {mod}_new #({pp}) u_new (' + ', '.join([f'.{n}({n})' for n in ins] + [f'.{n}({n})' for n in outs]) + ');')
w.append(f'  {mod}_old #({pp}) u_old (' + ', '.join([f'.{n}({n})' for n in ins] + [f'.{n}(mo_{n})' for n in outs]) + ');')
w.append('  longint unsigned mt_cyc, mt_bad;')
w.append('  initial begin mt_cyc = 0; mt_bad = 0; end')
w.append('  always @(posedge clk) begin')
w.append('    mt_cyc <= mt_cyc + 1;')
cond = ' || '.join(f'({n} != mo_{n})' for n in outs)
w.append(f'    if ({cond}) begin')
w.append('      mt_bad <= mt_bad + 1;')
w.append('      if (mt_bad < 10) begin')
w.append(f'        $display("MITER {mod}: cycle %0d differs", mt_cyc);')
for n in outs:
    w.append(f'        if ({n} != mo_{n}) $display("  {n}: new %h old %h", {n}, mo_{n});')
w.append('      end')
w.append('    end')
w.append('  end')
w.append(f'  final $display("MITER {mod}: %0d cycles, %0d with an output differing (%0d outputs compared)", mt_cyc, mt_bad, {len(outs)});')
w.append('endmodule')
open(f'{out}/{mod}_miter.sv', 'w').write('\n'.join(w) + '\n')
print(f'{mod}: {len(pnames)} parameters, {len(ins)} inputs, {len(outs)} outputs -> {out}')
